package com.github.guoyyit.causalbroadcastjava.store;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.github.guoyyit.causalbroadcastjava.model.BroadcastMessage;
import jakarta.annotation.PostConstruct;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Durable, restart-safe storage of all causal-broadcast state.
 * Skeleton: method contracts only.
 */
@Repository
public class DurableStore {

    private static final TypeReference<Map<String, Long>> CLOCK_TYPE = new TypeReference<>() {
    };

    private final JdbcTemplate jdbc;
    private final ObjectMapper objectMapper;

    public DurableStore(JdbcTemplate jdbc, ObjectMapper objectMapper) {
        this.jdbc = jdbc;
        this.objectMapper = objectMapper;
    }

    @PostConstruct
    public void initializeSchema() {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS members (
                    id VARCHAR(255) PRIMARY KEY,
                    gen INTEGER NOT NULL,
                    active BOOLEAN NOT NULL,
                    clock_json CLOB NOT NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS messages (
                    id VARCHAR(255) PRIMARY KEY,
                    sender_id VARCHAR(255) NOT NULL,
                    sender_key VARCHAR(255) NOT NULL,
                    seq BIGINT NOT NULL,
                    clock_json CLOB,
                    payload CLOB NOT NULL,
                    created_order BIGINT GENERATED BY DEFAULT AS IDENTITY
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS message_targets (
                    message_id VARCHAR(255) NOT NULL,
                    member_key VARCHAR(255) NOT NULL,
                    received BOOLEAN NOT NULL,
                    delivered BOOLEAN NOT NULL,
                    deliver_seq BIGINT,
                    PRIMARY KEY (message_id, member_key)
                )
                """);
        jdbc.execute("""
                CREATE INDEX IF NOT EXISTS idx_targets_member
                    ON message_targets (member_key, delivered, received)
                """);
    }

    public boolean memberExists(String memberId) {
        Integer count = jdbc.queryForObject(
                "SELECT COUNT(*) FROM members WHERE id = ?", Integer.class, memberId);
        return count != null && count > 0;
    }

    public Map<String, Object> findMemberRow(String memberId) {
        List<Map<String, Object>> rows = jdbc.queryForList(
                "SELECT id, gen, active, clock_json FROM members WHERE id = ?", memberId);
        return rows.isEmpty() ? null : rows.get(0);
    }

    public int maxGeneration(String memberId) {
        Integer max = jdbc.queryForObject(
                "SELECT COALESCE(MAX(gen), 0) FROM members WHERE id = ?",
                Integer.class, memberId);
        return max == null ? 0 : max;
    }

    public void insertMember(String memberId, String memberKey, String clockJson) {
        int separator = memberKey.lastIndexOf('#');
        int generation = Integer.parseInt(memberKey.substring(separator + 1));
        jdbc.update("""
                        MERGE INTO members (id, gen, active, clock_json)
                        KEY (id) VALUES (?, ?, TRUE, ?)
                        """,
                memberId, generation, clockJson);
    }

    public List<Map<String, Object>> listActiveMembers() {
        return jdbc.queryForList(
                "SELECT id, gen, active, clock_json FROM members WHERE active = TRUE ORDER BY id");
    }

    public String findMemberKey(String memberId) {
        List<String> keys = jdbc.query(
                "SELECT id, gen FROM members WHERE id = ?",
                (rs, rowNum) -> rs.getString("id") + "#" + rs.getInt("gen"),
                memberId);
        return keys.isEmpty() ? null : keys.get(0);
    }

    public void deactivateMember(String memberId) {
        jdbc.update("UPDATE members SET active = FALSE WHERE id = ?", memberId);
    }

    public void updateMemberClock(String memberId, String clockJson) {
        jdbc.update("UPDATE members SET clock_json = ? WHERE id = ?", clockJson, memberId);
    }

    public BroadcastMessage findMessage(String messageId) {
        List<BroadcastMessage> messages = jdbc.query(
                "SELECT id, sender_id, sender_key, seq, clock_json, payload "
                        + "FROM messages WHERE id = ?",
                (rs, rowNum) -> mapMessage(rs),
                messageId);
        if (messages.isEmpty()) {
            return null;
        }
        BroadcastMessage message = messages.get(0);
        List<String> targets = jdbc.queryForList(
                "SELECT member_key FROM message_targets WHERE message_id = ? ORDER BY member_key",
                String.class, messageId);
        return new BroadcastMessage(message.id(), message.senderKey(), message.senderId(),
                message.seq(), message.clockJson(), message.payload(), List.copyOf(targets));
    }

    public void insertMessage(BroadcastMessage message, List<String> targetKeys) {
        jdbc.update("""
                        INSERT INTO messages
                            (id, sender_id, sender_key, seq, clock_json, payload)
                        VALUES (?, ?, ?, ?, ?, ?)
                        """,
                message.id(), message.senderId(), message.senderKey(), message.seq(),
                message.clockJson(), message.payload());
        jdbc.batchUpdate("""
                        INSERT INTO message_targets
                            (message_id, member_key, received, delivered, deliver_seq)
                        VALUES (?, ?, FALSE, FALSE, NULL)
                        """,
                targetKeys, targetKeys.size(), (ps, memberKey) -> {
                    ps.setString(1, message.id());
                    ps.setString(2, memberKey);
                });
    }

    public boolean isDelivered(String memberKey, String messageId) {
        Integer count = jdbc.queryForObject(
                "SELECT COUNT(*) FROM message_targets "
                        + "WHERE message_id = ? AND member_key = ? AND delivered = TRUE",
                Integer.class, messageId, memberKey);
        return count != null && count > 0;
    }

    public boolean isReceived(String memberKey, String messageId) {
        Integer count = jdbc.queryForObject(
                "SELECT COUNT(*) FROM message_targets "
                        + "WHERE message_id = ? AND member_key = ? AND received = TRUE",
                Integer.class, messageId, memberKey);
        return count != null && count > 0;
    }

    /**
     * @return 1 when the target row exists (and is now marked received),
     *         0 when the message is not addressed to this member
     */
    public int markReceived(String memberKey, String messageId) {
        return jdbc.update(
                "UPDATE message_targets SET received = TRUE "
                        + "WHERE message_id = ? AND member_key = ? AND received = FALSE",
                messageId, memberKey);
    }

    public long nextDeliverSeq(String memberKey) {
        Long max = jdbc.queryForObject(
                "SELECT COALESCE(MAX(deliver_seq), 0) FROM message_targets WHERE member_key = ?",
                Long.class, memberKey);
        return (max == null ? 0L : max) + 1;
    }

    public void markDelivered(String memberKey, String messageId, long deliverSeq) {
        jdbc.update(
                "UPDATE message_targets SET delivered = TRUE, deliver_seq = ? "
                        + "WHERE message_id = ? AND member_key = ? AND delivered = FALSE",
                deliverSeq, messageId, memberKey);
    }

    public int markAllReceived() {
        return jdbc.update(
                "UPDATE message_targets SET received = TRUE WHERE received = FALSE");
    }

    public List<BroadcastMessage> findPendingMessages(String memberKey) {
        return jdbc.query("""
                        SELECT m.id, m.sender_id, m.sender_key, m.seq, m.clock_json, m.payload
                        FROM messages m
                        JOIN message_targets t
                            ON t.message_id = m.id
                        WHERE t.member_key = ? AND t.received = TRUE AND t.delivered = FALSE
                        ORDER BY m.created_order DESC
                        """,
                (rs, rowNum) -> mapMessage(rs),
                memberKey);
    }

    public List<DeliveredRecord> deliveredPage(String memberKey, long afterSeq, int limit) {
        return jdbc.query("""
                        SELECT m.id, m.sender_id, m.sender_key, m.seq, m.clock_json,
                               m.payload, t.deliver_seq
                        FROM message_targets t
                        JOIN messages m ON m.id = t.message_id
                        WHERE t.member_key = ? AND t.delivered = TRUE
                          AND t.deliver_seq > ?
                        ORDER BY t.deliver_seq
                        FETCH FIRST ? ROWS ONLY
                        """,
                (rs, rowNum) -> new DeliveredRecord(rs.getLong("deliver_seq"), mapMessage(rs)),
                memberKey, afterSeq, limit);
    }

    public List<String> candidateStableMessages(int limit) {
        return jdbc.queryForList("""
                        SELECT m.id FROM messages m
                        WHERE m.clock_json IS NOT NULL
                          AND NOT EXISTS (
                              SELECT 1 FROM message_targets t
                              WHERE t.message_id = m.id AND t.delivered = FALSE
                          )
                        ORDER BY m.created_order
                        FETCH FIRST ? ROWS ONLY
                        """,
                String.class, limit);
    }

    public void nullStableMessageClocks(List<String> messageIds) {
        if (messageIds.isEmpty()) {
            return;
        }
        jdbc.update("UPDATE messages SET clock_json = NULL WHERE id IN ("
                + placeholders(messageIds.size()) + ")",
                messageIds.toArray());
    }

    public long countNonNullClocks() {
        Long count = jdbc.queryForObject(
                "SELECT COUNT(*) FROM messages WHERE clock_json IS NOT NULL", Long.class);
        return count == null ? 0L : count;
    }

    public void deleteAllData() {
        jdbc.update("DELETE FROM message_targets");
        jdbc.update("DELETE FROM messages");
        jdbc.update("DELETE FROM members");
    }

    public String writeClock(Map<String, Long> clock) {
        try {
            return objectMapper.writeValueAsString(new LinkedHashMap<>(clock));
        } catch (Exception e) {
            throw new IllegalStateException("failed to serialize vector clock", e);
        }
    }

    public Map<String, Long> readClock(String clockJson) {
        if (clockJson == null || clockJson.isBlank()) {
            return Map.of();
        }
        try {
            Map<String, Long> parsed = objectMapper.readValue(clockJson, CLOCK_TYPE);
            return new LinkedHashMap<>(parsed);
        } catch (Exception e) {
            throw new IllegalStateException("failed to deserialize vector clock", e);
        }
    }

    private BroadcastMessage mapMessage(ResultSet rs) throws SQLException {
        String clockJson = rs.getString("clock_json");
        return new BroadcastMessage(
                rs.getString("id"),
                rs.getString("sender_key"),
                rs.getString("sender_id"),
                rs.getLong("seq"),
                clockJson,
                rs.getString("payload"),
                List.of());
    }

    private static String placeholders(int count) {
        return String.join(",", java.util.Collections.nCopies(count, "?"));
    }

    /** One row of a member's per-receiver delivered log. */
    public record DeliveredRecord(long deliverSeq, BroadcastMessage message) {
    }
}
